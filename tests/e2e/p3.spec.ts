import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { evaluateWorkbench } from '../../src/engine/src/workbench';

test('edits captured and dynamic attributes through the Worker and round trips P3 files', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.getByTestId('workspace-nav-projects').click();
  await page.getByTestId('p3-load-snapshot').click();
  await expect(page.getByTestId('workspace-objective')).toHaveText('6,900');
  await page.getByTestId('workspace-nav-team').click();
  await page.getByRole('combobox', { name: /^当前轴角色/ }).selectOption('support');
  await page.getByLabel('候选攻击力', { exact: true }).fill('1200');
  await expect(page.getByTestId('workspace-objective')).toHaveText('7,020');
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(page.getByTestId('workspace-objective')).toHaveText('6,900');
  await page.getByRole('button', { name: '重做', exact: true }).click();
  await expect(page.getByTestId('workspace-objective')).toHaveText('7,020');
  await page.getByLabel('候选攻击力', { exact: true }).fill('1000');
  await page.getByLabel('编辑 P3 定义', { exact: true }).selectOption('support-character');
  await page.getByLabel('效果2读取方式', { exact: true }).selectOption('dynamic');
  await expect(page.getByTestId('workspace-objective')).toHaveText('6,600');
  await page.getByLabel('效果2读取方式', { exact: true }).selectOption('source');
  await expect(page.getByTestId('workspace-objective')).toHaveText('6,900');
  const transfer = page.locator('[data-p3-instance]').filter({ has: page.getByLabel('修订 效果2', { exact: true }) });
  await transfer.getByRole('button', { name: '禁用来源实例', exact: true }).click();
  await expect(page.getByTestId('workspace-objective')).toHaveText('6,000');
  await transfer.getByRole('button', { name: '恢复来源实例', exact: true }).click();
  await expect(page.getByTestId('workspace-objective')).toHaveText('6,900');
  await transfer.getByLabel('修订 效果2', { exact: true }).fill('400');
  await transfer.getByRole('button', { name: '应用数值修订', exact: true }).click();
  await expect(page.getByTestId('workspace-objective')).toHaveText('7,200');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '保存轴项目', exact: true }).click();
  const download = await downloadPromise;
  const path = testInfo.outputPath('p3-capture-project.json'); await download.saveAs(path);
  const saved = JSON.parse(await readFile(path, 'utf8'));
  expect(saved.rulesVersion).toBe('workbench-p3');
  expect(evaluateWorkbench(saved).objectiveValue).toBe(7200);
  await page.reload();
  await page.getByRole('button', { name: '恢复上次编辑', exact: true }).click();
  await expect(page.getByTestId('workspace-objective')).toHaveText('7,200');
  await page.getByTestId('workspace-nav-projects').click();
  await page.getByRole('button', { name: '新建空轴', exact: true }).click();
  await page.getByLabel('导入轴项目文件', { exact: true }).setInputFiles(path);
  await expect(page.getByTestId('workspace-objective')).toHaveText('7,200');
  await page.getByTestId('workspace-nav-team').click();
  await page.getByText('属性读取与捕获轨迹', { exact: true }).click();
  await expect(page.getByRole('region', { name: '效果快照与历史', exact: true })).toContainText('记录之前');
  await page.screenshot({ path: testInfo.outputPath('p3-capture.png'), fullPage: true });
});

test('edits a settlement, filters history and diagnoses a true self-cycle', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.getByTestId('workspace-nav-projects').click();
  await page.getByTestId('p3-load-history').click();
  await expect(page.getByTestId('workspace-objective')).toHaveText('150');
  await expect(page.getByTestId('workspace-total')).toHaveText('1,350');
  await page.getByTestId('workspace-nav-team').click();
  await page.getByLabel('编辑 P3 定义', { exact: true }).selectOption('hit-one');
  await page.getByLabel('P3 节点1数值', { exact: true }).fill('120');
  await page.getByLabel('编辑 P3 定义', { exact: true }).selectOption('hit-four');
  await page.getByLabel('P3 节点1数值', { exact: true }).fill('240');
  await expect(page.getByTestId('workspace-objective')).toHaveText('180');
  await page.getByLabel('编辑 P3 定义', { exact: true }).selectOption('settlement');
  await page.getByLabel('历史观察定义', { exact: true }).selectOption('hit-one');
  await expect(page.getByTestId('workspace-objective')).toHaveText('60');
  await page.getByLabel('历史观察定义', { exact: true }).selectOption('');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '保存轴项目', exact: true }).click();
  const download = await downloadPromise;
  const path = testInfo.outputPath('p3-history-project.json'); await download.saveAs(path);
  expect(evaluateWorkbench(JSON.parse(await readFile(path, 'utf8'))).objectiveValue).toBe(180);
  await page.getByLabel('历史窗口结束', { exact: true }).fill('6001');
  await page.getByLabel('历史包含当前结算', { exact: true }).check();
  await expect(page.getByTestId('workspace-objective')).toHaveText('待确认');
  await page.getByLabel('导入轴项目文件', { exact: true }).setInputFiles(path);
  await expect(page.getByTestId('workspace-objective')).toHaveText('180');
  await page.screenshot({ path: testInfo.outputPath('p3-history.png'), fullPage: true });
});

test('creates an actual P3 effect on a real game build using the common forms', async ({ page }) => {
  await page.goto('/');
  await page.getByTestId('workspace-nav-projects').click();
  await page.getByRole('button', { name: '新建空轴', exact: true }).click();
  await page.getByTestId('workspace-nav-team').click();
  await page.getByLabel('游戏角色', { exact: true }).selectOption('jean');
  await page.getByRole('button', { name: '添加真实角色到当前轴', exact: true }).click();
  await page.getByRole('button', { name: '添加技能全部独立命中', exact: true }).click();
  await expect(page.getByTestId('workspace-total')).toHaveText('1,549.2331');
  await page.getByRole('button', { name: '当前轴明确采用 P3 规则', exact: true }).click();
  await page.getByLabel('效果来源角色', { exact: true }).selectOption({ index: 1 });
  await page.getByLabel('效果接收者', { exact: true }).selectOption('team');
  await page.getByLabel('效果固定增量', { exact: true }).fill('100');
  await page.getByRole('button', { name: '创建效果到来源武器', exact: true }).click();
  // Jean E9 4.964 * .5 defense * .9 resistance * 100 extra attack = 223.38.
  await expect(page.getByTestId('workspace-total')).toHaveText('1,772.6131');
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(page.getByTestId('workspace-total')).toHaveText('1,549.2331');
  await page.getByRole('button', { name: '重做', exact: true }).click();
  await expect(page.getByTestId('workspace-total')).toHaveText('1,772.6131');
});

