import { readDocument } from '../../helpers/browser-document';
import { existsSync, readFileSync } from 'node:fs';
import { expect, test } from '@playwright/test';
import type { CharacterMetadata, DamageCalculatorDocument, LocalAccount } from '@leyline/schema';
import { recordedVesnaDamage, vesnaRecording } from '../../helpers/recorded-vesna';

test('recorded Vesna goes through showcase confirmation, Worker comparison, file reopening and JSON-only edits', async ({ page }, info) => {
  test.skip(!existsSync(vesnaRecording), 'Requires the original authorized showcase response.');
  test.setTimeout(60000);
  const original = readFileSync(vesnaRecording, 'utf8'), uid = String(JSON.parse(original).uid);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route(`**/api/enka/${uid}`, route => route.fulfill({ contentType: 'application/json', body: original }));
  await page.setViewportSize({ width: 1536, height: 1050 });
  await page.goto('/');
  await page.getByTestId('workspace-nav-characters').click();
  await page.getByRole('button', { name: '展柜导入', exact: true }).click();
  const preview = page.getByRole('dialog', { name: '从角色展柜导入', exact: true });
  await preview.getByLabel('游戏 UID', { exact: true }).fill(uid);
  await preview.getByRole('button', { name: '查询角色展柜', exact: true }).click();
  await preview.getByRole('button', { name: '清空选择', exact: true }).click();
  await preview.getByRole('button', { name: '导入薇斯纳', exact: true }).click();
  const storage = () => page.evaluate(() => [localStorage.getItem('leyline-account-0.1.0'), localStorage.getItem('leyline-axis-recovery-0.1.0')]);
  const pending = (await storage())[0];
  expect(pending ? JSON.parse(pending).document.characters : []).toHaveLength(0);
  await preview.getByRole('button', { name: '确认导入 1 位角色', exact: true }).click();
  await expect(preview).toBeHidden();
  const before = await storage();
  const account: LocalAccount = await readDocument(page, 'account', before[0]!);
  expect(account.characters).toHaveLength(1);
  expect(account.artifacts).toHaveLength(5);
  expect(account.characters[0].showcase?.build).toMatchObject({ constellation: 2, level: 90, refinement: 1, weapon: { id: 'beyondthechrysalis' } });

  await page.getByTestId('workspace-nav-calculator').click();
  const calculator = page.getByRole('region', { name: '伤害计算' });
  const select = (name: string) => calculator.getByRole('combobox', { name, exact: true });
  const button = (name: string) => calculator.getByRole('button', { name, exact: true });
  await button('选择角色').click();
  await button('展柜').click();
  await button('选择薇斯纳').click();
  await expect(calculator.locator('.configuration-row.compact')).toContainText('蝶变');
  await expect(button('更换武器')).toHaveCount(0);
  await button('选择伤害').click();
  await calculator.getByRole('dialog', { name: '选择伤害' }).locator('[data-output-id="vesna.skill.param5.stellar-swirl"]').click();
  const buffDialog = page.getByRole('dialog', { name: '选择增益' });
  await button('选择增益').click();
  await expect(select('星辉状态')).toHaveValue('stellar-swirl');
  await expect(select('薇斯纳战技姿态')).toHaveValue('true');
  for (const option of await buffDialog.getByRole('checkbox').all()) await option.check();
  await expect(calculator.getByRole('spinbutton', { name: '律令层数', exact: true })).toHaveValue('6');
  await button('应用增益').click();
  const number = (id: string) => expect.poll(async () => Number((await calculator.getByTestId(id).textContent())?.replaceAll(',', '')));
  const baseline = recordedVesnaDamage(1), candidate = recordedVesnaDamage(2);
  await button('计算伤害').click();
  await number('calculator-expected').toBeCloseTo(baseline, 5);
  await number('calculator-value').toBeCloseTo(recordedVesnaDamage(1, 1, true, 'critical'), 5);
  await select('暴击').selectOption('expected');
  await button('选择增益').click();
  await select('蝶变 / 叛弃之风（10秒内）').selectOption('');
  await button('应用增益').click();
  await button('计算伤害').click();
  await expect(calculator.getByTestId('calculator-value')).toHaveText('需补充条件');
  await expect(calculator.getByRole('list', { name:'未完成的计算条件' })).toContainText('蝶变 / 叛弃之风');
  await button('补充增益条件').click();
  await buffDialog.getByRole('checkbox', { name: /叛弃之风/ }).check();
  await button('应用增益').click();
  await button('计算伤害').click();
  await number('calculator-value').toBeCloseTo(baseline, 5);
  const critCard = calculator.locator('.factor-card').filter({ has: page.locator('summary', { hasText: '暴击区' }) });
  await critCard.locator('summary').click();
  await expect(critCard).toContainText('忠忱之风');
  await expect(critCard).toContainText('56%');
  const loyalWind = buffDialog.getByRole('checkbox', { name: /忠忱之风/ });
  await button('选择增益').click();
  await expect(loyalWind).toBeChecked();
  await expect(loyalWind.locator('..').locator('img').first()).toBeVisible();
  await loyalWind.uncheck();
  await page.keyboard.press('Escape');
  await expect(button('选择增益')).toBeFocused();
  await number('calculator-value').toBeCloseTo(baseline, 5);
  await button('选择增益').click();
  await loyalWind.uncheck();
  await buffDialog.getByRole('button', { name: '应用增益' }).click();
  await button('计算伤害').click();
  await number('calculator-expected').toBeCloseTo(recordedVesnaDamage(1,1,false), 5);
  await button('选择增益').click();
  await loyalWind.check();
  await page.screenshot({ path: info.outputPath('buff-picker.png') });
  await button('应用增益').click();
  await button('计算伤害').click();
  await number('calculator-value').toBeCloseTo(baseline, 5);
  await button('设为比较基准').click();
  await button('编辑角色配置').click();
  const editor = calculator.getByRole('dialog', { name:'薇斯纳 · 角色配置' });
  await editor.getByRole('button', { name:'查看生之花详情' }).click();
  await page.keyboard.press('Escape');
  await expect(editor.getByRole('button', { name:'查看生之花详情' })).toBeFocused();
  await page.screenshot({ path:info.outputPath('calculator-build-editor.png') });
  await page.setViewportSize({width:390,height:844});
  expect(await editor.evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true);
  const heading = editor.getByRole('heading', { name:'薇斯纳 · 角色配置' });
  expect(await heading.evaluate(node => node.getBoundingClientRect().height)).toBeLessThanOrEqual(32);
  await page.screenshot({ path:info.outputPath('calculator-build-editor-mobile.png') });
  await page.setViewportSize({width:1536,height:1050});
  await editor.getByRole('button', { name:'查看生之花详情' }).press('Shift+F10');
  await page.getByRole('menuitem', { name:'卸下' }).click();
  await expect(editor.getByRole('button', { name:'装备生之花' })).toBeVisible();
  await button('精炼2阶').click();
  await page.keyboard.press('Escape');
  await page.getByRole('dialog', { name:'有未保存的修改' }).getByRole('button', { name:'放弃修改' }).click();
  await expect(button('编辑角色配置')).toBeFocused();
  await button('编辑角色配置').click();
  await expect(editor.getByRole('button', { name:'查看生之花详情' })).toBeVisible();
  await expect(button('精炼1阶')).toHaveAttribute('aria-pressed','true');
  await button('精炼2阶').click();
  await editor.getByRole('button', { name:'保存', exact:true }).click();
  await button('重算候选').click();
  await number('calculator-delta').toBeCloseTo(candidate - baseline, 5);
  const download = page.waitForEvent('download');
  await button('导出计算文件').click();
  const saved = await download;
  await saved.saveAs(info.outputPath('vesna-comparison.json'));
  const document: DamageCalculatorDocument = await readDocument(page, 'damage-calculator', readFileSync(info.outputPath('vesna-comparison.json'), 'utf8'));
  expect(document.baseline!.candidate.actors[0].build!.refinement).toBe(1);
  expect(document.project.candidate.actors[0].build!.refinement).toBe(2);
  expect(document.project.timeline[0].damage?.outputId).toBe('vesna.skill.param5.stellar-swirl');
  await calculator.getByLabel('打开伤害计算文件', { exact: true }).setInputFiles(info.outputPath('vesna-comparison.json'));
  await number('calculator-value').toBeCloseTo(candidate, 5);
  await number('calculator-delta').toBeCloseTo(candidate - baseline, 5);
  await page.screenshot({ path: info.outputPath('vesna-comparison.png'), fullPage: true });

  await button('结束对照').click();
  await calculator.getByText('角色定义', { exact:true }).click();
  const definitionDownload = page.waitForEvent('download');
  await button('导出角色定义副本').click();
  const definitionFile = await definitionDownload;
  await definitionFile.saveAs(info.outputPath('vesna-original.character.json'));
  const modified: CharacterMetadata = JSON.parse(readFileSync(info.outputPath('vesna-original.character.json'), 'utf8'));
  modified.talents.find(talent => talent.id === 'vesna.skill')!.parameters.find(parameter => parameter.id === 'param5')!.values[9] *= 1.1;
  await calculator.getByLabel('导入计算器角色定义', { exact: true }).setInputFiles({ name: 'vesna-adjusted.character.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(modified, null, 2) + '\n') });
  await number('calculator-value').toBeCloseTo(recordedVesnaDamage(2, 1.1), 5);
  await expect(button('选择伤害')).toHaveAttribute('data-output-id', 'vesna.skill.param5.stellar-swirl');
  expect(await storage()).toEqual(before);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await calculator.evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true);
  const navigation = page.getByRole('button', { name: '打开功能导航', exact: true });
  await navigation.click();
  const entry = page.locator('.nav-group[data-domain="project"]').getByTestId('workspace-nav-calculator');
  await expect(entry).toHaveAttribute('aria-current', 'page');
  await entry.press('Escape');
  await expect(navigation).toBeFocused();
  expect(errors).toEqual([]);
});
