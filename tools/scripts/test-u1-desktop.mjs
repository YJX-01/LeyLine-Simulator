import { _electron as electron, expect } from '@playwright/test';
import { mkdir, readFile, writeFile, mkdtemp } from 'node:fs/promises';
import { resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { desktopExecutable } from './desktop-location.mjs';
const directory = resolve('artifacts/u1-desktop-validation');
await mkdir(directory, { recursive: true });
const userData = await mkdtemp(resolve(tmpdir(), 'leyline-u1-'));
const executable = await desktopExecutable(false);
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ executablePath: executable, args: ['--smoke', `--user-data-dir=${userData}`], env, timeout: 30000 });
try {
  const page = await app.firstWindow();
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].show());
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await expect(page.getByTestId('workspace-nav-characters')).toHaveAttribute('aria-current', 'page');
  await page.getByTestId('workspace-nav-artifacts').click();
  await page.getByRole('button', { name: '导入莫娜圣遗物', exact: true }).click();
  await page.getByLabel('导入莫娜圣遗物文件', { exact: true }).setInputFiles(resolve('.references/artifacts_mona.json'));
  await expect(page.getByLabel('莫娜导入预览', { exact: true })).toContainText('新增 458 件');
  await page.getByRole('button', { name: '确认导入 458 件五星圣遗物', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('搜索圣遗物', { exact: true }).fill('琴');
  await expect(page.locator('.inventory-count')).toContainText('筛选结果 0 件');
  await page.getByLabel('搜索圣遗物', { exact: true }).fill('');
  await page.getByRole('button', { name: '生之花', exact: true }).click();
  await expect(page.locator('.inventory-count')).toContainText('筛选结果 86 件');
  await expect.poll(() => page.locator('.inventory-card .game-icon > img').first().evaluate(image => image.complete && image.naturalWidth > 0)).toBe(true);
  await page.locator('.inventory-card').first().click();
  await expect(page.getByRole('dialog')).toContainText('4,780');
  await page.getByRole('button', { name: '编辑圣遗物', exact: true }).click();
  await page.getByLabel('强化等级', { exact: true }).fill('16');
  await page.keyboard.press('Escape');
  await expect(page.locator('.inventory-card').first().locator('.artifact-level')).toHaveText('20');
  await page.getByRole('button', { name: '手动添加圣遗物', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('预览词条');
  await page.keyboard.press('Escape');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: resolve(directory, 'actual-inventory.png'), fullPage: true });
  const file = resolve(directory, 'actual-account.json');
  await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, file);
  await page.getByRole('button', { name: '导航 设置', exact: true }).click();
  await page.getByRole('button', { name: '保存账号资料', exact: true }).click();
  await expect.poll(async () => JSON.parse(await readFile(file, 'utf8').catch(() => '{}')).artifacts?.length).toBe(458);
  await page.getByRole('button', { name: '打开 / 切换账号', exact: true }).click();
  await expect(page.getByLabel('账号管理', { exact: true })).toContainText('458 件圣遗物');
  await page.getByTestId('workspace-nav-characters').click();
  await page.getByRole('button', { name: '手动添加', exact: true }).click();
  await page.getByRole('button', { name: '选择游戏角色', exact: true }).click();
  for (const name of ['芙宁娜', '丝柯克']) {
    await page.getByLabel('搜索游戏角色', { exact: true }).fill(name);
    await expect.poll(() => page.locator('.catalog-options .game-icon > img').first().evaluate(image => {
      if (!image.complete) return false;
      const canvas = document.createElement('canvas'); canvas.width = 128; canvas.height = 128;
      const context = canvas.getContext('2d'); context.drawImage(image,0,0,128,128);
      const pixels = context.getImageData(0,0,128,128).data;
      let opaque = false; for (let index = 3; index < pixels.length; index += 4) if (pixels[index] >= 128) { opaque = true; break; }
      return image.naturalWidth === 128 && image.naturalHeight === 128 && opaque && image.src.includes('?v=');
    })).toBe(true);
  }
  await page.screenshot({ path: resolve(directory, 'verified-portrait.png') });
  await page.keyboard.press('Escape'); await page.keyboard.press('Escape');
  await page.getByTestId('workspace-nav-team').click();
  await page.getByRole('button', { name: '＋ 从账号选择队员', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('账号还没有角色资料');
  await page.keyboard.press('Escape');
  await page.getByTestId('workspace-nav-timeline').click();
  await expect(page.getByLabel('剪辑式时间轴编辑', { exact: true })).toBeVisible();
  await page.screenshot({ path: resolve(directory, 'empty-axis.png'), fullPage: true });
  // The documented public showcase is a separate actual case, never mixed with the user's inventory.
  await page.getByRole('button', { name: '导航 设置', exact: true }).click();
  await page.getByRole('button', { name: '新建账号', exact: true }).click();
  await page.getByTestId('workspace-nav-characters').click();
  await page.getByRole('button', { name: '网络导入', exact: true }).click();
  const enka = page.getByRole('dialog', { name: '从 Enka 展柜导入', exact: true });
  await enka.getByLabel('游戏 UID', { exact: true }).fill('618285856');
  await enka.getByRole('button', { name: '查询角色展柜', exact: true }).click();
  await expect.poll(() => enka.locator('.import-row').count(), { timeout: 25000 }).toBeGreaterThan(0);
  const imported = await enka.locator('.import-row input:checked').count();
  await enka.getByRole('button', { name: `确认导入 ${imported} 位角色`, exact: true }).click();
  await expect(enka).toHaveCount(0);
  await expect(page.locator('.account-editor')).toContainText('公开展柜快照');
  const networkAccount = await page.evaluate(() => JSON.parse(localStorage.getItem('leyline-account-v1')));
  if (networkAccount.artifacts.length || networkAccount.characters.length !== imported) throw new Error('Showcase snapshots entered physical inventory');
  await page.screenshot({ path: resolve(directory, 'enka-showcase.png'), fullPage: true });
  if (errors.length) throw new Error(JSON.stringify(errors));
  await writeFile(resolve(directory, 'report.json'), JSON.stringify({ status: 'passed', executable, actualInventory: 458, enkaProfiles: imported, checks: ['preview-before-import', 'current-owner-search-separate-from-source-note', 'slot-filter', 'packaged-offline-artifact-image', 'square-portrait-real-pixels', 'artifact-edit-cancel', 'manual-entry-visible', 'native-account-save-open', 'empty-account-no-invented-characters', 'empty-editing-desk', 'desktop-live-enka-preview-confirm', 'showcase-inventory-isolation'], gaps: ['private Mona inventory has no verified matching UID; actual action records unavailable; no numerical or full-axis acceptance claimed'] }, null, 2));
  console.log('U1 desktop actual inventory tasks passed.');
} finally { await app.close(); }
